export const dict: Record<Locale, Record<TKey, string>> = { zh, en };

export type Translate = (
  key: TKey,
  params?: Record<string, string | number>,
) => string;

/** 极简插值：只认 {name}，不做复数/性别，够用且可预测 */
export function interpolate(
  template: string,
  params?: Record<string, string | number>,
): string {
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (whole, name: string) => {
    const v = params[name];
    return v === undefined ? whole : String(v);
  });
}

export function makeT(locale: Locale): Translate {
  const table = dict[locale] ?? dict.zh;
  return (key, params) => interpolate(table[key] ?? key, params);
}
